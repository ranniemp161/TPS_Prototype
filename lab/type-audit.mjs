/* Type audit across all pages. node lab/type-audit.mjs  -> lab/type-audit.csv + lab/type-audit.md */
import { chromium } from 'playwright-core';
import { pathToFileURL } from 'node:url';
import fs from 'node:fs';
const pages = ['index','what-we-do','programmes','about','faqs','who-comes-into-your-home','single-treatments','build-your-programme','gifts'];
const vps = [[1440,900],[390,844]];
const SEL = 'h1,h2,h3,.display,.script,.lede,.body,p,.tg__t,.tg__s,.card__title,.pg-price__days,.pg-price__num,.dk-step__t,.step__note,.dk-legal,.capture__note,.pg-same__note,.cta__meta,button,.btn,nav .tab';
const SMALL = ['dk-legal','capture__note','pg-same__note','cta__meta'];

function measure(SEL) {
  const out = []; let navDone = false;
  for (const e of document.querySelectorAll(SEL)) {
    const inChrome = e.closest('header.nav, footer.sf');
    const isTab = e.matches('nav .tab');
    if (inChrome && !(isTab && !navDone)) continue;
    if (!e.offsetParent && getComputedStyle(e).position !== 'fixed') continue;
    const r = e.getBoundingClientRect(); if (r.height === 0) continue;
    const c = getComputedStyle(e);
    if (c.visibility === 'hidden' || c.display === 'none') continue;
    const text = e.textContent.replace(/\s+/g, ' ').trim();
    if (!text) continue;
    if (isTab) navDone = true;
    const sec = e.closest('[data-section-name]');
    const sid = e.closest('section[id]');
    const cls = (e.getAttribute('class') || '');
    let role;
    if (isTab) role = 'nav';
    else if (e.matches('h1')) role = 'page title';
    else if (e.matches('.script')) role = 'Quentin script line';
    else if (e.matches('.tg__t,.card__title,.dk-step__t')) role = 'choice name';
    else if (e.matches('.tg__s,.step__note')) role = 'choice sub line';
    else if (e.matches('.dk-legal,.capture__note,.pg-same__note,.cta__meta')) role = 'small print';
    else if (e.matches('button,.btn')) role = 'label/button';
    else if (e.matches('.pg-price__days,.pg-price__num')) role = 'price';
    else if (e.matches('h2,h3,.display')) role = 'section heading';
    else role = 'body';
    out.push({ section: sec ? sec.getAttribute('data-section-name') : (sid ? '#' + sid.id : ''), tag: e.tagName.toLowerCase(), classes: cls, role,
      size: Math.round(parseFloat(c.fontSize) * 10) / 10, family: c.fontFamily.split(',')[0].replace(/["']/g, '').trim(), weight: c.fontWeight, text: text.slice(0, 40) });
  }
  return out;
}

const b = await chromium.launch({ channel: 'chrome' });
const rows = [];
for (const [w, h] of vps) {
  for (const pg of pages) {
    const p = await b.newPage({ viewport: { width: w, height: h } });
    await p.goto(pathToFileURL(process.cwd() + '/index/' + pg + '.html').href);
    await p.evaluate(() => document.fonts.ready); await p.waitForTimeout(1500);
    const add = (state, list) => list.forEach(r => rows.push({ page: pg, viewport: `${w}x${h}`, state, ...r }));
    add('load', await p.evaluate(measure, SEL));
    if (pg === 'build-your-programme') {
      const nxt = await p.$('.dk-next');
      if (nxt) { try { await nxt.click({ timeout: 3000 }); await p.waitForTimeout(1500);
        const seen = new Set(rows.filter(r => r.page === pg && r.viewport === `${w}x${h}`).map(r => r.section + r.classes + r.text));
        add('after-next', (await p.evaluate(measure, SEL)).filter(r => !seen.has(r.section + r.classes + r.text))); } catch (e) { console.log('next click failed', e.message); } }
    }
    await p.close();
  }
}
await b.close();

const esc = v => '"' + String(v).replace(/"/g, '""') + '"';
const cols = ['page','viewport','state','section','tag','classes','role','size','family','weight','text'];
fs.writeFileSync('lab/type-audit.csv', cols.join(',') + '\n' + rows.map(r => cols.map(c => esc(r[c])).join(',')).join('\n'));

// summary
let md = '# Type audit\n\nComputed px, one decimal. Generated by lab/type-audit.mjs. Rows: ' + rows.length + '\n\n';
md += '## 1. Page title vs largest section heading\n\n| Page | Viewport | Page title (h1) | Largest heading | Where | Flag |\n|---|---|---|---|---|---|\n';
for (const [w, h] of vps) for (const pg of pages) {
  const rs = rows.filter(r => r.page === pg && r.viewport === `${w}x${h}`);
  const t = rs.filter(r => r.role === 'page title').sort((a, b) => b.size - a.size)[0];
  const hs = rs.filter(r => r.role === 'section heading').sort((a, b) => b.size - a.size)[0];
  const flag = t && hs && hs.size > t.size ? 'LOWER HEADING LARGER' : (!t ? 'no h1 visible' : '');
  md += `| ${pg} | ${w} | ${t ? t.size + ' (' + t.section + ')' : 'none'} | ${hs ? hs.size : 'none'} | ${hs ? hs.section + ' / ' + hs.tag + '.' + hs.classes.split(' ')[0] : ''} | ${flag} |\n`;
}
md += '\n## 2. Distinct sizes by role\n';
const roles = ['page title','section heading','Quentin script line','body','choice name','choice sub line','small print','label/button','price','nav'];
for (const [w, h] of vps) {
  md += `\n### ${w}px wide\n`;
  for (const role of roles) {
    const rs = rows.filter(r => r.role === role && r.viewport === `${w}x${h}`);
    if (!rs.length) continue;
    md += `\n**${role}**\n\n| px | Pages | Sections | Count |\n|---|---|---|---|\n`;
    const sizes = [...new Set(rs.map(r => r.size))].sort((a, b) => a - b);
    for (const s of sizes) { const m = rs.filter(r => r.size === s);
      const pgs = [...new Set(m.map(r => r.page))]; const secs = [...new Set(m.map(r => r.page + ': ' + r.section))];
      md += `| ${s} | ${pgs.join(', ')} | ${secs.slice(0, 12).join('; ')}${secs.length > 12 ? '; +' + (secs.length - 12) + ' more' : ''} | ${m.length} |\n`; }
  }
}
fs.writeFileSync('lab/type-audit.md', md);
console.log('rows', rows.length);
